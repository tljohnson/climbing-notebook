// Test-only host probe. Compiled against the already-resolved ZIPFoundation sources.
import Foundation
import CryptoKit
import ZIPFoundation

enum ProbeFailure: Error { case assertion(String) }
func require(_ condition: Bool, _ message: String) throws {
    if !condition { throw ProbeFailure.assertion(message) }
}

let chunkSize = 1024 * 1024
let largeSize: Int64 = (1 << 32) + 123
let block = Data((0..<chunkSize).map { UInt8($0 % 251) })
let marker = Data("CF-05A offset sentinel\n".utf8)
func hex(_ digest: SHA256.Digest) -> String {
    digest.map { String(format: "%02x", $0) }.joined()
}

func create(_ url: URL, method: CompressionMethod) throws {
    let archive = try Archive(url: url, accessMode: .create)
    var count: Int64 = 0
    var hash = SHA256()
    try archive.addEntry(with: "synthetic.bin", type: .file, uncompressedSize: largeSize,
                         compressionMethod: method, bufferSize: chunkSize) { position, size in
        try require(position == count && size <= chunkSize, "provider position/buffer")
        let bytes = size == chunkSize ? block : Data(block.prefix(size))
        hash.update(data: bytes)
        count += Int64(bytes.count)
        return bytes
    }
    try require(count == largeSize, "generated byte count")
    try archive.addEntry(with: "after.txt", type: .file, uncompressedSize: Int64(marker.count),
                         compressionMethod: .none, bufferSize: chunkSize) { position, size in
        marker.subdata(in: Int(position)..<Int(position) + size)
    }
    print("GENERATED \(url.lastPathComponent) bytes=\(count) sha256=\(hex(hash.finalize()))")
}

func verify(_ url: URL) throws {
    var expectedHash = SHA256()
    var remaining = largeSize
    while remaining > 0 {
        let size = Int(min(Int64(chunkSize), remaining))
        expectedHash.update(data: size == chunkSize ? block : Data(block.prefix(size)))
        remaining -= Int64(size)
    }
    let expected = hex(expectedHash.finalize())
    let archive = try Archive(url: url, accessMode: .read)
    try require(Array(archive).map(\.path) == ["synthetic.bin", "after.txt"], "names/count/order")
    for entry in archive {
        let targetSize = entry.path == "synthetic.bin" ? largeSize : Int64(marker.count)
        try require(entry.type == .file && entry.uncompressedSize == UInt64(targetSize), "entry metadata")
        var count: Int64 = 0
        var hash = SHA256()
        let crc = try archive.extract(entry, bufferSize: chunkSize) { bytes in
            try require(bytes.count <= chunkSize && Int64(bytes.count) <= targetSize - count,
                        "stream buffer/inflated byte limit")
            hash.update(data: bytes)
            count += Int64(bytes.count)
        }
        let digest = hex(hash.finalize())
        try require(count == targetSize && crc == entry.checksum, "stream size/CRC")
        try require(digest == (entry.path == "synthetic.bin" ? expected : hex(SHA256.hash(data: marker))),
                    "SHA-256 content identity")
        print("VERIFIED \(url.lastPathComponent) \(entry.path) uncompressed=\(count) compressed=\(entry.compressedSize) crc32=\(String(crc, radix: 16)) sha256=\(digest)")
    }
}

try require(CommandLine.arguments.count == 3, "usage: probe create|verify scratch-directory")
let root = URL(fileURLWithPath: CommandLine.arguments[2], isDirectory: true)
switch CommandLine.arguments[1] {
case "create":
    for (name, method) in [("swift-stored.zip", CompressionMethod.none), ("swift-deflated.zip", .deflate)] {
        let url = root.appendingPathComponent(name)
        try create(url, method: method)
        try verify(url)
    }
case "verify":
    for name in ["python-stored.zip", "python-deflated.zip"] {
        try verify(root.appendingPathComponent(name))
    }
default: throw ProbeFailure.assertion("unknown operation")
}
